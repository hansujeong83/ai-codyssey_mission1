#!/usr/bin/env bash
# Run from the repository root: bash scripts/capture_mission1.sh
# Captures real command output from this machine. It never fabricates results.
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
OUT="$ROOT/docs/evidence/terminal-session.txt"
mkdir -p "$ROOT/docs/evidence"
: > "$OUT"
exec > >(tee -a "$OUT") 2>&1

PASS=0
FAIL=0
WORK="$(mktemp -d)"
STAMP="$(date -Is 2>/dev/null || date)"
TAG="codyssey-evidence-$$"
WEB="${TAG}-web"
BIND="${TAG}-bind"
VOL="${TAG}-volume"

cleanup() {
  docker rm -f "$WEB" "$BIND" "${TAG}-ubuntu" "${TAG}-volume-a" "${TAG}-volume-b" >/dev/null 2>&1 || true
  docker volume rm "$VOL" >/dev/null 2>&1 || true
  rm -rf "$WORK"
}
trap cleanup EXIT

section() { printf '\n\n===== %s =====\n' "$1"; }
check() {
  local label="$1"; shift
  printf '\n$'; printf ' %q' "$@"; printf '\n'
  if "$@"; then
    PASS=$((PASS + 1))
    printf '[PASS] %s\n' "$label"
  else
    FAIL=$((FAIL + 1))
    printf '[FAIL] %s\n' "$label"
  fi
}

section "Mission 1 real execution evidence"
echo "Captured at: $STAMP"
echo "Repository: $ROOT"
echo "This file is generated by commands executed on the learner's computer."

section "1. OS, shell, versions, Docker daemon"
check "OS information" uname -a
echo "SHELL=${SHELL:-unknown}"
check "Python version" python3 --version
check "Git version" git --version
check "Docker CLI version" docker --version
if docker info; then
  PASS=$((PASS + 1)); echo "[PASS] Docker daemon is reachable"
else
  FAIL=$((FAIL + 1)); echo "[FAIL] Docker daemon is not reachable"
  echo "Docker-dependent tests are skipped. Start Docker Desktop or the institution-approved runtime, then run this script again."
  exit 1
fi

section "2. Terminal operations and paths"
mkdir -p "$WORK/practice"
cd "$WORK/practice"
echo "Absolute path:"; pwd
echo "Relative path example: from practice/, ../ means the parent directory."
echo "Directory listing including hidden entries:"; ls -la
printf 'Codyssey Mission 1\n' > sample.txt
echo "File contents:"; cat sample.txt
cp sample.txt copy.txt
mv copy.txt renamed.txt
echo "After copy and rename:"; ls -la
rm renamed.txt
echo "After delete:"; ls -la
cd "$ROOT"

section "3. File and directory permissions"
mkdir -p "$WORK/permission-dir"
: > "$WORK/permission-file.txt"
echo "Before:"; ls -l "$WORK/permission-file.txt"; ls -ld "$WORK/permission-dir"
chmod 640 "$WORK/permission-file.txt"
chmod 750 "$WORK/permission-dir"
echo "After:"; ls -l "$WORK/permission-file.txt"; ls -ld "$WORK/permission-dir"
echo "640 = owner rw-, group r--, others ---; 750 directory = owner rwx, group r-x, others ---."

section "4. hello-world and Ubuntu container lifecycle"
check "hello-world" docker run --rm hello-world
UBUNTU="${TAG}-ubuntu"
check "Start Ubuntu container" docker run -d --name "$UBUNTU" ubuntu:24.04 sleep 300
check "Ubuntu OS details" docker exec "$UBUNTU" sh -lc 'cat /etc/os-release; pwd; ls -la; echo "container works"'
echo "Container logs:"; docker logs "$UBUNTU" || true
echo "Container resource snapshot:"; docker stats --no-stream "$UBUNTU" || true
echo "Running containers:"; docker ps
echo "All containers:"; docker ps -a
docker rm -f "$UBUNTU"

section "5. Custom NGINX image, port mapping, logs and health"
check "Build custom image" docker build -t codyssey-mission1-web:1.0 .
check "Run web container" docker run -d --name "$WEB" -p 8080:80 codyssey-mission1-web:1.0
sleep 2
echo "HTTP response from http://localhost:8080:"
if curl --fail --silent --show-error http://localhost:8080/; then
  PASS=$((PASS + 1)); echo "[PASS] Port mapping 8080:80"
else
  FAIL=$((FAIL + 1)); echo "[FAIL] Port mapping 8080:80"
fi
echo "Container logs:"; docker logs "$WEB" || true
echo "Container status:"; docker ps --filter "name=$WEB"
echo "Image list:"; docker images codyssey-mission1-web
docker rm -f "$WEB"

section "6. Bind mount live-change verification"
cp -R "$ROOT/app" "$WORK/app"
check "Start bind-mounted NGINX" docker run -d --name "$BIND" -p 8081:80 --mount "type=bind,source=$WORK/app,target=/usr/share/nginx/html,readonly" nginx:1.27-alpine
sleep 2
echo "Before host-side edit:"
curl --fail --silent --show-error http://localhost:8081/ | grep -F "Codyssey Mission 1"
printf '\n<!-- bind-mount-change-verified -->\n' >> "$WORK/app/index.html"
echo "After host-side edit:"
if curl --fail --silent --show-error http://localhost:8081/ | grep -F "bind-mount-change-verified"; then
  PASS=$((PASS + 1)); echo "[PASS] Host file change appeared in container"
else
  FAIL=$((FAIL + 1)); echo "[FAIL] Bind mount live change"
fi
docker rm -f "$BIND"

section "7. Named volume persistence after container deletion"
check "Create named volume" docker volume create "$VOL"
docker run -d --name "${TAG}-volume-a" -v "$VOL":/data ubuntu:24.04 sleep 300
docker exec "${TAG}-volume-a" sh -lc 'echo persistent-data-survived > /data/proof.txt'
echo "First container wrote:"; docker exec "${TAG}-volume-a" cat /data/proof.txt
docker rm -f "${TAG}-volume-a"
docker run -d --name "${TAG}-volume-b" -v "$VOL":/data ubuntu:24.04 sleep 300
RESULT="$(docker exec "${TAG}-volume-b" cat /data/proof.txt)"
echo "Second container read after first container deletion: $RESULT"
if [[ "$RESULT" == "persistent-data-survived" ]]; then
  PASS=$((PASS + 1)); echo "[PASS] Named volume persisted data"
else
  FAIL=$((FAIL + 1)); echo "[FAIL] Named volume persistence"
fi
docker rm -f "${TAG}-volume-b"
docker volume rm "$VOL"

section "8. Compose configuration"
if docker compose version; then
  COMPOSE_PROJECT="${TAG}-compose"
  echo "Starting Compose service on host port 8082."
  if WEB_PORT=8082 docker compose -p "$COMPOSE_PROJECT" up -d --build; then
    docker compose -p "$COMPOSE_PROJECT" ps
    docker compose -p "$COMPOSE_PROJECT" logs --no-color
    if curl --fail --silent --show-error http://localhost:8082/ >/dev/null; then
      PASS=$((PASS + 1)); echo "[PASS] Compose web service responded on port 8082"
    else
      FAIL=$((FAIL + 1)); echo "[FAIL] Compose web service HTTP check"
    fi
    WEB_PORT=8082 docker compose -p "$COMPOSE_PROJECT" down
  else
    FAIL=$((FAIL + 1)); echo "[FAIL] Compose up"
    WEB_PORT=8082 docker compose -p "$COMPOSE_PROJECT" down >/dev/null 2>&1 || true
  fi
else
  echo "[INFO] Docker Compose plugin is unavailable; optional bonus test not run."
fi

section "9. Git repository status (credentials are not printed)"
git status --short --branch
git remote -v
git branch --show-current
git log -1 --oneline
if git remote get-url origin >/dev/null 2>&1; then
  echo "Checking read access to origin (no files are pushed):"
  git ls-remote origin HEAD
else
  echo "[INFO] No origin remote configured in this local checkout."
fi

section "Result summary"
echo "PASS=$PASS"
echo "FAIL=$FAIL"
if [[ "$FAIL" -eq 0 ]]; then
  echo "RESULT=PASS (all executed required checks succeeded)"
else
  echo "RESULT=PARTIAL (review [FAIL] entries above and rerun)"
  exit 1
fi
echo "Evidence log: docs/evidence/terminal-session.txt"
echo "Screenshots must still be captured manually; this script does not create or imitate screenshots."
